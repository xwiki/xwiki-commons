package org.xwiki.tool.sbom.internal;

import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;
import java.util.UUID;

import com.fasterxml.jackson.core.JsonProcessingException;
import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.databind.node.ArrayNode;
import com.fasterxml.jackson.databind.node.ObjectNode;

/**
 * Makes reproducible a CycloneDX SBOM listing the packages bundled in an artifact, so that building the artifact twice
 * from the same sources gives the same SBOM. It's needed for the SBOM generated by {@code pnpm sbom}, which sets the
 * current date as timestamp and a random serial number, and which walks the packages concurrently: the order of the
 * components and the dependency graph vary from one run to the next, since it records a package reached from several
 * parents as a dependency of the first parent reaching it only. So the normalized SBOM:
 * <ul>
 * <li>has no timestamp (it's optional);</li>
 * <li>has its components sorted by {@code bom-ref};</li>
 * <li>has, instead of the (possibly incomplete) dependency graph, the component it describes depending on every
 * component, which is what matters for an artifact bundling them all;</li>
 * <li>has a serial number derived from its content, as the CycloneDX Maven plugin does.</li>
 * </ul>
 *
 * @version $Id$
 */
public class SBOMNormalizer
{
    private static final String SERIAL_NUMBER = "serialNumber";

    private static final List<String> HEADERS = List.of("$schema", "bomFormat", "specVersion");

    private static final String BOM_REF = "bom-ref";

    private static final String COMPONENTS = "components";

    private static final String DEPENDENCIES = "dependencies";

    private static final ObjectMapper MAPPER = new ObjectMapper();

    /**
     * @param bom the SBOM to normalize, left unchanged
     * @return the normalized SBOM
     * @throws JsonProcessingException when failing to serialize the SBOM to compute its serial number
     */
    public ObjectNode normalize(ObjectNode bom) throws JsonProcessingException
    {
        ObjectNode normalized = bom.deepCopy();
        normalized.remove(SERIAL_NUMBER);
        if (normalized.get("metadata") instanceof ObjectNode metadata) {
            metadata.remove("timestamp");
        }

        List<JsonNode> components = new ArrayList<>();
        normalized.withArrayProperty(COMPONENTS).forEach(components::add);
        components.sort(Comparator.comparing(component -> component.path(BOM_REF).asText()));
        normalized.putArray(COMPONENTS).addAll(components);

        String describedRef = normalized.at("/metadata/component/bom-ref").asText(null);
        if (describedRef != null) {
            ObjectNode dependency = MAPPER.createObjectNode();
            dependency.put("ref", describedRef);
            ArrayNode dependsOn = dependency.putArray("dependsOn");
            components.forEach(component -> dependsOn.add(component.path(BOM_REF).asText()));
            normalized.putArray(DEPENDENCIES).add(dependency);
        } else {
            normalized.remove(DEPENDENCIES);
        }

        UUID serialNumber = UUID.nameUUIDFromBytes(MAPPER.writeValueAsBytes(normalized));
        // Keep the serial number next to the other header fields, where the CycloneDX tools write it.
        ObjectNode result = MAPPER.createObjectNode();
        for (String header : HEADERS) {
            if (normalized.has(header)) {
                result.set(header, normalized.get(header));
            }
        }
        result.put(SERIAL_NUMBER, "urn:uuid:" + serialNumber);
        result.setAll(normalized);

        return result;
    }
}
