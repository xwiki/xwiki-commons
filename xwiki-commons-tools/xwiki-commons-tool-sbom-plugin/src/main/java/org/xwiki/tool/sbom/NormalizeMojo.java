package org.xwiki.tool.sbom;

import java.io.File;
import java.io.IOException;
import java.nio.file.Files;

import org.apache.maven.plugin.AbstractMojo;
import org.apache.maven.plugin.MojoExecutionException;
import org.apache.maven.plugins.annotations.LifecyclePhase;
import org.apache.maven.plugins.annotations.Mojo;
import org.apache.maven.plugins.annotations.Parameter;
import org.xwiki.tool.sbom.internal.SBOMNormalizer;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.databind.node.ObjectNode;

/**
 * Makes reproducible a CycloneDX SBOM listing the packages bundled in the artifact (e.g. the one generated by
 * {@code pnpm sbom}), before it's embedded in the artifact, typically in its {@code META-INF/sbom/} directory where
 * the {@code enrich} goal finds it. See {@link SBOMNormalizer} for what is changed. The source SBOM is deleted once
 * normalized, and the target SBOM is deleted when there's no source SBOM: a build that doesn't generate the source SBOM
 * (e.g. because its generation is skipped) doesn't embed a stale one, left by a previous build.
 *
 * @version $Id$
 * @since 18.10.0RC1
 */
@Mojo(name = "normalize", defaultPhase = LifecyclePhase.PREPARE_PACKAGE, threadSafe = true)
public class NormalizeMojo extends AbstractMojo
{
    private static final ObjectMapper MAPPER = new ObjectMapper();

    /**
     * The SBOM to normalize, deleted once normalized.
     */
    @Parameter(required = true)
    private File sourceFile;

    /**
     * Where to write the normalized SBOM.
     */
    @Parameter(required = true)
    private File targetFile;

    /**
     * Whether the generation of the source SBOM is skipped on purpose, in which case its absence is not reported. The
     * target SBOM is still deleted.
     */
    @Parameter(property = "xwiki.sbom.npm.skip", defaultValue = "false")
    private boolean skip;

    @Override
    public void execute() throws MojoExecutionException
    {
        String errorMessage = String.format("Failed to normalize the SBOM [%s]", this.sourceFile);
        try {
            if (this.skip || !this.sourceFile.isFile()) {
                if (!this.skip) {
                    getLog().warn(String.format("No SBOM found at [%s], so the artifact won't embed [%s].",
                        this.sourceFile, this.targetFile));
                }
                Files.deleteIfExists(this.targetFile.toPath());
                return;
            }

            if (!(MAPPER.readTree(this.sourceFile) instanceof ObjectNode bom)) {
                throw new MojoExecutionException(errorMessage + ": it's not a JSON object.");
            }
            Files.createDirectories(this.targetFile.toPath().getParent());
            MAPPER.writerWithDefaultPrettyPrinter().writeValue(this.targetFile, new SBOMNormalizer().normalize(bom));
            Files.delete(this.sourceFile.toPath());
        } catch (IOException e) {
            throw new MojoExecutionException(errorMessage, e);
        }
    }
}
